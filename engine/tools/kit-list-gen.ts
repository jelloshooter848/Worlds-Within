import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { format, resolveConfig } from 'prettier';

/**
 * The generated list of kit hooks, `engine/tools/kit-list.ts`: one import per `kits/<name>/kit.ts`
 * found on disk, so a new kit needs its hook file and `pnpm docs:gen`, never a hand edit to an
 * engine table. `pnpm docs:check` (and `kits.test.ts`) fail when the list is out of date.
 */

export const KIT_LIST = 'engine/tools/kit-list.ts';

/** The kit names that have a hook: folders under `kits/` with a `kit.ts`, sorted. */
export function kitNamesOnDisk(root: string): string[] {
  const dir = join(root, 'kits');
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && existsSync(join(dir, e.name, 'kit.ts')))
    .map((e) => e.name)
    .sort();
}

/** A kebab-case kit name as an identifier: `top-down` -> `topDown`. */
function identifier(name: string): string {
  const camel = name.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
  return /^[0-9]/.test(camel) ? `kit${camel}` : camel;
}

/** What `kit-list.ts` should hold for the hooks under `root`, formatted with the repo's Prettier settings. */
export async function kitListText(root: string): Promise<string> {
  const names = kitNamesOnDisk(root);
  const text = [
    '// Generated by `pnpm docs:gen` (engine/tools/kit-list-gen.ts) from every `kits/<name>/kit.ts`.',
    '// Do not edit: add a kit by giving it a `kit.ts` hook and running `pnpm docs:gen`.',
    "import type { KitDef } from '@engine/core/kit';",
    ...names.map((n) => `import { kit as ${identifier(n)} } from '@kits/${n}/kit';`),
    '',
    '/** Every kit hook in the repo, by kit name. */',
    `export const KIT_HOOKS: readonly KitDef[] = [${names.map(identifier).join(', ')}];`,
    '',
  ].join('\n');
  const abs = join(root, KIT_LIST);
  const config = (await resolveConfig(abs, { editorconfig: true })) ?? {};
  return format(text, { ...config, parser: 'typescript', filepath: abs });
}

/** Writes `kit-list.ts` under `root` if it changed; returns whether it did. */
export async function writeKitList(root: string): Promise<boolean> {
  const text = await kitListText(root);
  const abs = join(root, KIT_LIST);
  if (existsSync(abs) && readFileSync(abs, 'utf8') === text) return false;
  writeFileSync(abs, text);
  return true;
}

/** Whether `kit-list.ts` under `root` is what the generator makes now. */
export async function kitListIsCurrent(root: string): Promise<boolean> {
  const abs = join(root, KIT_LIST);
  return existsSync(abs) && readFileSync(abs, 'utf8') === (await kitListText(root));
}
